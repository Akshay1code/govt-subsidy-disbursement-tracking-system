    @Override
    @Transactional
    public EligibilityEngineScoreDTO saveFields(
            Long userId,
            ApplicationFieldValueRequestDTO req) {

        if (req == null
                || req.getSchemeCode() == null
                || req.getSchemeCode().trim().isEmpty()) {

            throw new BadRequestException("Scheme code is required");
        }

        Users user = userRepo.findById(userId)
                .orElseThrow(() ->
                        new ResourceNotFoundException("User not found"));

        Schemes scheme = schemeRepo.findBySchemeCode(req.getSchemeCode().trim())
                .orElseThrow(() ->
                        new ResourceNotFoundException(
                                "Scheme not found with code: "
                                        + req.getSchemeCode()));

        Application app = applicationRepo
                .findByUser_IdAndScheme_SchemeCode(
                        userId,
                        scheme.getSchemeCode())
                .map(existingApplication -> {

                    if (existingApplication.getStatus() != null
                            && existingApplication.getStatus()
                            != ApplicationStatus.DRAFT
                            && existingApplication.getStatus()
                            != ApplicationStatus.PENDING) {

                        throw new DuplicateResourceException(
                                "An application already exists for this scheme. "
                                        + "Please continue or cancel the existing application."
                        );
                    }

                    if (existingApplication.getFieldValues() != null) {
                        existingApplication.getFieldValues().clear();
                    }

                    if (existingApplication.getDocuments() != null) {
                        existingApplication.getDocuments().clear();
                    }

                    existingApplication.setStatus(ApplicationStatus.DRAFT);

                    return existingApplication;
                })
                .orElseGet(() -> {

                    Application newApplication = new Application();

                    newApplication.setApplicationCode(
                            "APP-"
                                    + UUID.randomUUID()
                                    .toString()
                                    .substring(0, 8)
                                    .toUpperCase()
                    );

                    newApplication.setUser(user);
                    newApplication.setScheme(scheme);
                    newApplication.setStatus(ApplicationStatus.DRAFT);

                    return newApplication;
                });

        List<FieldValueRequestDTO> submittedFields =
                req.getFields() == null
                        ? List.of()
                        : req.getFields();

        List<ApplicationFieldValue> fieldValues =
                new ArrayList<>();

        for (FieldValueRequestDTO dto : submittedFields) {

            if (dto == null || dto.getFieldName() == null) {
                continue;
            }

            ApplicationFieldValue field =
                    new ApplicationFieldValue();

            field.setFieldName(dto.getFieldName());
            field.setFieldValue(dto.getValue());
            field.setApplication(app);

            fieldValues.add(field);
        }

        app.setFieldValues(fieldValues);

        Application saved = applicationRepo.save(app);

        /*
         * Before running the eligibility engine, make sure all
         * required eligibility fields have been provided.
         */
        String missingField =
                findMissingEligibilityField(
                        scheme,
                        submittedFields);

        if (missingField != null) {

            return new EligibilityEngineScoreDTO(
                    false,
                    0.0,
                    "Missing value for field: " + missingField
            );
        }

        /*
         * Run eligibility engine after all required fields
         * have been supplied.
         */
        double score = check.validateFields(saved.getId());

        if (score < scheme.getMinimumEligibleScore()) {

            return new EligibilityEngineScoreDTO(
                    false,
                    score,
                    "You are not eligible"
            );
        }

        /*
         * Applicant passed the eligibility check.
         */
        app.setStatus(ApplicationStatus.UNDER_REVIEW);

        applicationRepo.save(app);

        /*
         * Create workflow for the application after it
         * successfully passes eligibility.
         */
        workflowService.createWorkflow(app);

        return new EligibilityEngineScoreDTO(
                true,
                score,
                "You are eligible"
        );
    }

    @Override
    @Transactional
    public void cancelApplication(
            Long userId,
            Long applicationId) {

        if (applicationId == null) {
            throw new BadRequestException(
                    "Application ID is required");
        }

        Application application = applicationRepo
                .findById(applicationId)
                .orElseThrow(() ->
                        new ResourceNotFoundException(
                                "No application found for this application ID"));

        if (application.getUser() == null
                || application.getUser().getId() == null
                || !application.getUser()
                .getId()
                .equals(userId)) {

            throw new BadRequestException(
                    "You are not allowed to cancel this application");
        }

        if (application.getStatus() != ApplicationStatus.DRAFT
                && application.getStatus() != ApplicationStatus.PENDING) {

            throw new BadRequestException(
                    "Only draft applications can be cancelled");
        }

        applicationRepo.delete(application);

        com.example.gov_scheme_backend.entities.AuditLog audit = com.example.gov_scheme_backend.entities.AuditLog.builder()
                .auditId(UUID.randomUUID().toString())
                .user(application.getUser())
                .action(com.example.gov_scheme_backend.enums.AuditAction.DELETE)
                .description("Cancelled application ID: " + applicationId)
                .build();
        auditLogRepo.save(audit);
    }

    @Override
    @Transactional
    public void submitApplication(
            Long userId,
            String schemeCode) {

        if (schemeCode == null
                || schemeCode.trim().isEmpty()) {

            throw new BadRequestException(
                    "Scheme code is required");
        }

        Application application =
                applicationRepo
                        .findByUser_IdAndScheme_SchemeCode(
                                userId,
                                schemeCode.trim())
                        .orElseThrow(() ->
                                new ResourceNotFoundException(
                                        "No application found for this scheme"));

        if (application.getStatus() != ApplicationStatus.DRAFT
                && application.getStatus() != ApplicationStatus.PENDING) {

            throw new BadRequestException(
                    "Application has already been submitted");
        }

        application.setStatus(
                ApplicationStatus.SUBMITTED);

        applicationRepo.save(application);

        com.example.gov_scheme_backend.entities.AuditLog audit = com.example.gov_scheme_backend.entities.AuditLog.builder()
                .auditId(UUID.randomUUID().toString())
                .user(application.getUser())
                .action(com.example.gov_scheme_backend.enums.AuditAction.UPDATE)
                .description("Submitted application for scheme: " + schemeCode)
                .build();
        auditLogRepo.save(audit);
    }

    private String findMissingEligibilityField(
            Schemes scheme,
            List<FieldValueRequestDTO> submittedFields) {

        if (scheme == null
                || scheme.getEligibilityRules() == null
                || scheme.getEligibilityRules().isEmpty()) {

            return null;
        }

        Set<String> providedFields =
                submittedFields.stream()
                        .filter(dto ->
                                dto != null
                                        && dto.getFieldName() != null)
                        .map(dto ->
                                dto.getFieldName().name())
                        .collect(Collectors.toSet());

        for (var rule : scheme.getEligibilityRules()) {

            if (rule == null
                    || rule.getFieldName() == null) {

                continue;
            }

            if (!providedFields.contains(
                    rule.getFieldName().name())) {

                return rule.getFieldName().name();
            }
        }

        return null;
    }

